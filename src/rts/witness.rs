use super::{load_image, native_hashes, script, RtsHashes, RtsOrders, RtsSimPlugin};
use bevy::prelude::*;
use replay::Command;
use sim::fixed::{from_int, ONE};
use std::path::{Path, PathBuf};

const IMAGE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/testdata/rts/duel-routes.osdt");
const ORDERS_PATH: &str = "testdata/rts/duel-routes.orders";
const HASHES_PATH: &str = "testdata/rts/duel-routes.hashes";
const ORDERS: &str = include_str!("../../testdata/rts/duel-routes.orders");
const HASHES: &str = include_str!("../../testdata/rts/duel-routes.hashes");
const REFERENCE_TICKS: usize = 3200;

fn expected() -> Vec<(u32, u64)> {
    HASHES
        .lines()
        .map(|line| {
            let (tick, hash) = line.split_once(' ').expect("tick and hash");
            (tick.parse().expect("tick"), u64::from_str_radix(hash, 16).expect("hash"))
        })
        .collect()
}

fn bevy_hashes(orders: Vec<(u32, Command)>, ticks: usize) -> Vec<(u32, u64)> {
    let mut app = App::new();
    app.add_plugins((MinimalPlugins, RtsSimPlugin { image: PathBuf::from(IMAGE) }))
        .insert_resource(RtsOrders::new(orders));
    for _ in 0..ticks {
        app.world_mut().run_schedule(FixedUpdate);
    }
    app.world().resource::<RtsHashes>().0.clone()
}

fn flip_first_order(text: &str) -> String {
    let mut lines: Vec<String> = text.lines().map(str::to_string).collect();
    let first = lines.iter_mut().find(|line| !line.trim().is_empty()).expect("an order");
    let mut fields: Vec<String> = first.split_whitespace().map(str::to_string).collect();
    let x: i32 = fields[3].parse().expect("x");
    fields[3] = (x + ONE).to_string();
    *first = fields.join(" ");
    lines.join("\n")
}

fn grid_centre_orders() -> String {
    let sim = load_image(Path::new(IMAGE));
    let grid = sim.grid();
    let (x, y) = (from_int((grid.w / 2) as i32), from_int((grid.h / 2) as i32));
    format!("0 order_all 0 {x} {y}\n0 order_all 1 {x} {y}\n640 order_all 1 {x} {y}\n")
}

#[test]
fn fixed_update_hash_matches_native_every_tick() {
    let orders = script::parse(ORDERS).expect("orders");
    let expected = expected();
    assert!(!expected.is_empty(), "reference hashes are generated by the ignored write test");
    let ticks = expected.len();
    assert_eq!(native_hashes(load_image(Path::new(IMAGE)), &orders, ticks), expected, "native sim drifted from the reference");
    assert_eq!(bevy_hashes(orders, ticks), expected, "Bevy FixedUpdate hash differs from the native reference");
}

#[test]
fn red_one_flipped_order_changes_the_hash() {
    let expected = expected();
    assert!(!expected.is_empty(), "reference hashes are generated by the ignored write test");
    let flipped = script::parse(&flip_first_order(ORDERS)).expect("flipped orders");
    assert_ne!(bevy_hashes(flipped, expected.len()), expected);
}

